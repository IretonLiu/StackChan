#pragma once

#include "face_preset_evaluator.h"
#include "motion_response.h"

#include <pet/face_schema.generated.h>

#include <array>
#include <cstdint>
#include <string_view>

namespace pet::preset {

/** A typed compiled target; `element_index` selects a polygon vertex when required. */
struct FacePoseTargetDefinition {
    uint8_t node_index      = 0;
    FacePoseChannel channel = FacePoseChannel::TransformTranslationX;
    uint8_t element_index   = 0;
    float value             = 0.0f;
    MotionResponseProfile response{};
};

/** A named goal state generated by the host compiler. */
struct FacePoseDefinition {
    const char* id                          = nullptr;
    const FacePoseTargetDefinition* targets = nullptr;
    uint8_t target_count                    = 0;
};

struct FacePoseRuntimeTarget {
    uint8_t node_index      = 0;
    FacePoseChannel channel = FacePoseChannel::TransformTranslationX;
    uint8_t element_index   = 0;
    float target            = 0.0f;
    MotionResponseProfile response{};
    MotionResponseState state{};
};

/**
 * Caller-owned current state for the selected pose. No heap allocation or
 * runtime parsing is used. Set `response_function` to replace spring dynamics.
 */
struct FacePoseRuntime {
    std::array<FacePoseRuntimeTarget, kMaxFacePoseTargets> targets{};
    uint8_t target_count                     = 0;
    MotionResponseFunction response_function = advanceCriticallyDampedSpring;
};

/**
 * Selects a generated named pose. Matching channels retain their current state
 * so that changing goals is interruptible rather than a visual jump.
 */
[[nodiscard]] bool selectFacePose(const FacePresetDefinition& preset, std::string_view pose_id,
                                  const FacePresetEvaluation& base, FacePoseRuntime& runtime);

/**
 * Advances all selected targets and writes them to `evaluation`.
 *
 * A target that cannot advance, or that would make the polygon geometry invalid,
 * is settled at its last valid value instead of rolling back every target and
 * retrying the same rejected step forever. Other targets may continue, so the
 * caller should render when `changed` is true and should treat a false return as
 * a degraded/recoverable frame rather than a reason to stop updating the face.
 */
[[nodiscard]] bool advanceFacePose(FacePoseRuntime& runtime, float delta_seconds, FacePresetEvaluation& evaluation,
                                   bool* changed = nullptr);

}  // namespace pet::preset
