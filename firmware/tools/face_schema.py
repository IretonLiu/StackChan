#!/usr/bin/env python3
"""Load and render the shared face primitive schema.

The schema is the single source of truth for animatable channels, their value
ranges, preset capacities and authored polygon defaults. The C++ header is
generated by ``generate_face_schema.py`` and checked in so host tools can build
without a code-generation step; ``face_schema_test.py`` fails if it drifts.
"""
import json
import math
from pathlib import Path

SCHEMA_PATH = Path(__file__).resolve().parents[1] / "pet_faces" / "face_schema.json"
MAX_CXX_FLOAT = 3.4028234663852886e38

CHANNEL_KINDS = (None, "circle", "rounded_polygon")

# C++ symbol names are part of the generated contract, not the numeric values.
RANGE_CPP = {
    "coordinate": ("pet::preset", "kCoordinateMinimum", "kCoordinateMaximum"),
    "rotation_degrees": ("pet::preset", "kRotationMinimum", "kRotationMaximum"),
    "scale": ("pet::preset", "kScaleMinimum", "kScaleMaximum"),
    "circle_radius": ("pet::preset", "kRadiusMinimum", "kRadiusMaximum"),
    "corner_roundness": ("pet::shape", "kMinCornerRoundness", "kMaxCornerRoundness"),
    "corner_cap_tension": ("pet::shape", "kMinCapTension", "kMaxCapTension"),
    "edge_bulge": ("pet::shape", "kMinEdgeBulge", "kMaxEdgeBulge"),
    "edge_handle": ("pet::shape", "kMinEdgeHandle", "kMaxEdgeHandle"),
    "opacity": ("pet::preset", "kOpacityMinimum", "kOpacityMaximum"),
}
DEFAULT_CPP = {
    "corner_roundness": "kDefaultCornerRoundness",
    "corner_cap_tension": "kDefaultCapTension",
    "edge_bulge": "kDefaultEdgeBulge",
    "edge_handle": "kDefaultEdgeHandle",
}
LIMIT_CPP = {
    "max_nodes": ("pet::preset", "kMaxFacePresetNodes"),
    "max_polygon_corners": ("pet::shape", "kMaxRoundedPolygonCorners"),
    "max_poses": ("pet::preset", "kMaxFacePresetPoses"),
    "max_pose_targets": ("pet::preset", "kMaxFacePoseTargets"),
    "max_animation_goals": ("pet::preset", "kMaxFaceAnimationGoals"),
    "max_motion_programs": ("pet::preset", "kMaxFaceMotionPrograms"),
    "max_motion_tracks": ("pet::preset", "kMaxFaceMotionTracks"),
    "max_motion_keyframes": ("pet::preset", "kMaxFaceMotionKeyframes"),
}


class SchemaError(ValueError):
    pass


def fail(where, message):
    raise SchemaError(f"{where}: {message}")


def obj(value, where):
    if not isinstance(value, dict):
        fail(where, "must be an object")
    return value


def require_keys(value, allowed, where):
    unknown = set(value) - set(allowed)
    if unknown:
        fail(where, "unknown field(s): " + ", ".join(sorted(unknown)))
    missing = set(allowed) - set(value)
    if missing:
        fail(where, "missing field(s): " + ", ".join(sorted(missing)))


def number(value, where):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        fail(where, "must be a finite number")
    result = float(value)
    if not math.isfinite(result) or abs(result) > MAX_CXX_FLOAT:
        fail(where, "must be a finite number")
    return result


def positive_int(value, where):
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        fail(where, "must be a positive integer")
    return value


def load_schema(path=SCHEMA_PATH):
    try:
        value = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as error:
        raise SchemaError(f"{path}: {error}") from error

    value = obj(value, str(path))
    require_keys(value, {"version", "limits", "ranges", "defaults", "channels"}, str(path))
    if value["version"] != 1:
        fail(str(path) + ".version", "must be 1")

    limits = obj(value["limits"], str(path) + ".limits")
    require_keys(limits, set(LIMIT_CPP), str(path) + ".limits")
    limits = {key: positive_int(limits[key], f"{path}.limits.{key}") for key in LIMIT_CPP}

    ranges = obj(value["ranges"], str(path) + ".ranges")
    require_keys(ranges, set(RANGE_CPP), str(path) + ".ranges")
    parsed_ranges = {}
    for key in RANGE_CPP:
        entry = obj(ranges[key], f"{path}.ranges.{key}")
        require_keys(entry, {"minimum", "maximum"}, f"{path}.ranges.{key}")
        minimum = number(entry["minimum"], f"{path}.ranges.{key}.minimum")
        maximum = number(entry["maximum"], f"{path}.ranges.{key}.maximum")
        if minimum >= maximum:
            fail(f"{path}.ranges.{key}", "minimum must be less than maximum")
        parsed_ranges[key] = {"minimum": minimum, "maximum": maximum}

    defaults = obj(value["defaults"], str(path) + ".defaults")
    require_keys(defaults, set(DEFAULT_CPP), str(path) + ".defaults")
    parsed_defaults = {}
    for key in DEFAULT_CPP:
        default = number(defaults[key], f"{path}.defaults.{key}")
        bounds = parsed_ranges[key]
        if not bounds["minimum"] <= default <= bounds["maximum"]:
            fail(f"{path}.defaults.{key}", "must be inside its authored range")
        parsed_defaults[key] = default

    channels = value["channels"]
    if not isinstance(channels, list) or not channels:
        fail(str(path) + ".channels", "must be a non-empty array")
    parsed_channels = []
    seen_ids, seen_enums = set(), set()
    for index, raw in enumerate(channels):
        where = f"{path}.channels[{index}]"
        raw = obj(raw, where)
        require_keys(raw, {"id", "enum", "kind", "element", "range"}, where)
        channel_id = raw["id"]
        enum_name = raw["enum"]
        if not isinstance(channel_id, str) or not channel_id:
            fail(where + ".id", "must be a non-empty string")
        if not isinstance(enum_name, str) or not enum_name or not enum_name.isidentifier():
            fail(where + ".enum", "must be a C++ identifier")
        if channel_id in seen_ids:
            fail(where + ".id", "duplicates another channel id")
        if enum_name in seen_enums:
            fail(where + ".enum", "duplicates another enum name")
        seen_ids.add(channel_id)
        seen_enums.add(enum_name)
        if raw["kind"] not in CHANNEL_KINDS:
            fail(where + ".kind", "must be null, circle or rounded_polygon")
        if not isinstance(raw["element"], bool):
            fail(where + ".element", "must be a boolean")
        if raw["range"] not in parsed_ranges:
            fail(where + ".range", "must name a range")
        parsed_channels.append(
            {
                "id": channel_id,
                "enum": enum_name,
                "kind": raw["kind"],
                "element": raw["element"],
                "range": raw["range"],
            }
        )

    return {
        "version": 1,
        "limits": limits,
        "ranges": parsed_ranges,
        "defaults": parsed_defaults,
        "channels": parsed_channels,
    }


def cpp_float(value):
    text = f"{value:.9g}"
    if "e" not in text and "E" not in text and "." not in text:
        text += ".0"
    return text + "f"


def append_aligned(lines, declarations):
    width = max(len(name) for _, name, _ in declarations)
    for type_name, name, value in declarations:
        lines.append(f"inline constexpr {type_name} {name.ljust(width)} = {value};")


def render_header(schema):
    lines = [
        "// Generated by tools/generate_face_schema.py from pet_faces/face_schema.json. Do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace pet::preset {",
        "",
        "/** One scalar control exposed by the fixed-capacity face primitive vocabulary. */",
        "enum class FacePoseChannel : uint8_t {",
    ]
    for channel in schema["channels"]:
        lines.append(f"    {channel['enum']},")
    lines.extend(["};", ""])

    append_aligned(
        lines,
        [
            ("uint8_t", name, str(schema["limits"][key]))
            for key, (namespace, name) in LIMIT_CPP.items()
            if namespace == "pet::preset"
        ],
    )
    lines.append("")
    append_aligned(
        lines,
        [
            ("float", name, cpp_float(schema["ranges"][key][bound]))
            for key, (namespace, min_name, max_name) in RANGE_CPP.items()
            if namespace == "pet::preset"
            for bound, name in (("minimum", min_name), ("maximum", max_name))
        ],
    )
    lines.extend(["", "}  // namespace pet::preset", "", "namespace pet::shape {", ""])

    shape_limits = [
        ("std::size_t", name, str(schema["limits"][key]))
        for key, (namespace, name) in LIMIT_CPP.items()
        if namespace == "pet::shape"
    ]
    append_aligned(lines, shape_limits)
    lines.append("")
    append_aligned(
        lines,
        [
            ("float", name, cpp_float(schema["ranges"][key][bound]))
            for key, (namespace, min_name, max_name) in RANGE_CPP.items()
            if namespace == "pet::shape"
            for bound, name in (("minimum", min_name), ("maximum", max_name))
        ],
    )
    lines.append("")
    append_aligned(
        lines,
        [("float", name, cpp_float(schema["defaults"][key])) for key, name in DEFAULT_CPP.items()],
    )
    lines.extend(["", "}  // namespace pet::shape", ""])
    return "\n".join(lines)
